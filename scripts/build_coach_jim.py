"""Turn the Coach Jim artwork into a TS module the app can bundle.

Usage (from web/):  python scripts/build_coach_jim.py ../avatar-template/coach.svg
Writes src/components/coach-jim/art.ts with:
  COACH_JIM_SVG   full layered SVG (animated by CoachJim.tsx)
  COACH_JIM_FACE  data URL of the idle face, for small chat avatars
"""
import json
import sys
import xml.etree.ElementTree as E
from pathlib import Path
from urllib.parse import quote

SVG_NS = "http://www.w3.org/2000/svg"
E.register_namespace("", SVG_NS)
E.register_namespace("xlink", "http://www.w3.org/1999/xlink")

MOUTHS = ["mouth-" + m for m in "X A B C D E F G H smile grin frown".split()]
FACE_VIEWBOX = "285 45 430 430"


def load(path):
    root = E.parse(path).getroot()
    for attr in ("width", "height", "id", "data-name"):
        root.attrib.pop(attr, None)
    # the artwork still uses the old layer name; normalise it
    for el in root.iter():
        if el.get("id") == "eyes-white":
            el.set("id", "eye-whites")
    # prefix gradient ids so they can't clash with other SVGs on the page (charts etc.)
    defs = {el.get("id") for d in root.iter(f"{{{SVG_NS}}}defs") for el in d.iter() if el.get("id")}
    href = "{http://www.w3.org/1999/xlink}href"
    for el in root.iter():
        if el.get("id") in defs:
            el.set("id", "cj-" + el.get("id"))
        for attr in ("fill", "stroke"):
            v = el.get(attr, "")
            if v.startswith("url(#") and v[5:-1] in defs:
                el.set(attr, f"url(#cj-{v[5:-1]})")
        if el.get(href, "").lstrip("#") in defs:
            el.set(href, "#cj-" + el.get(href).lstrip("#"))
    return root


def face(root):
    root.set("viewBox", FACE_VIEWBOX)
    head = next(el for el in root.iter() if el.get("id") == "head")
    for child in list(head):
        if child.get("id") in MOUTHS[1:] + ["lids-half", "lids-closed"]:
            head.remove(child)
    return "data:image/svg+xml," + quote(E.tostring(root, encoding="unicode"), safe=" =:/\"',.-")


def main(src):
    src = Path(src)
    full = E.tostring(load(src), encoding="unicode")
    out = Path(__file__).resolve().parent.parent / "src/components/coach-jim/art.ts"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "// Generated by scripts/build_coach_jim.py from avatar-template/coach.svg. Do not edit by hand.\n"
        f"export const COACH_JIM_SVG = {json.dumps(full)};\n\n"
        f"export const COACH_JIM_FACE = {json.dumps(face(load(src)))};\n",
        encoding="utf-8",
    )
    print(f"wrote {out} ({out.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main(sys.argv[1])
