"""Pre-render Coach Jim's spoken lines with a neural voice (edge-tts, no API key).

Reads every `id` + `spoken` pair from src/data/coach-responses.ts and writes
  public/voice/<id>.mp3          the audio
  src/data/coach-voice.ts        word timings, so the mouth follows the audio

Usage (from web/):  python scripts/build_coach_voice.py [--voice en-GB-RyanNeural]
Rerun after changing any `spoken` line.
"""
import argparse
import asyncio
import json
import pathlib
import re

import edge_tts

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src/data/coach-responses.ts"
OUT_AUDIO = ROOT / "public/voice"
OUT_TS = ROOT / "src/data/coach-voice.ts"


def spoken_lines() -> dict[str, str]:
    text = SRC.read_text(encoding="utf-8")
    lines = {}
    for block in re.split(r"\n  \{\n", text):
        m_id = re.search(r'^\s*id: "([^"]+)"', block, re.M)
        m_sp = re.search(r'spoken:\s*\n?\s*"((?:[^"\\]|\\.)*)"', block)
        if m_id and m_sp:
            lines[m_id.group(1)] = json.loads(f'"{m_sp.group(1)}"')
    return lines


async def render(key: str, line: str, voice: str, rate: str, pitch: str) -> dict:
    comm = edge_tts.Communicate(line, voice, rate=rate, pitch=pitch, boundary="WordBoundary")
    audio = bytearray()
    words = []
    async for chunk in comm.stream():
        if chunk["type"] == "audio":
            audio.extend(chunk["data"])
        elif chunk["type"] == "WordBoundary":
            # offsets are in 100-nanosecond units
            words.append([round(chunk["offset"] / 1e4), round(chunk["duration"] / 1e4), chunk["text"]])
    (OUT_AUDIO / f"{key}.mp3").write_bytes(audio)
    end = words[-1][0] + words[-1][1] if words else 0
    return {"ms": end, "words": words}


async def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--voice", default="en-GB-RyanNeural")
    ap.add_argument("--rate", default="+0%")
    ap.add_argument("--pitch", default="-2Hz")
    a = ap.parse_args()

    OUT_AUDIO.mkdir(parents=True, exist_ok=True)
    clips = {}
    for key, line in spoken_lines().items():
        clips[key] = await render(key, line, a.voice, a.rate, a.pitch)
        print(f"{key:12} {clips[key]['ms'] / 1000:5.1f}s  {len(clips[key]['words'])} words")

    body = ",\n".join(f"  {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}" for k, v in clips.items())
    OUT_TS.write_text(
        "// Generated by scripts/build_coach_voice.py. Do not edit.\n"
        f"// Voice: {a.voice}. Audio in public/voice/<id>.mp3; words are [startMs, durationMs, text].\n\n"
        "export type VoiceClip = { ms: number; words: [number, number, string][] };\n\n"
        f"export const coachVoice: Record<string, VoiceClip> = {{\n{body},\n}};\n",
        encoding="utf-8",
    )


asyncio.run(main())
